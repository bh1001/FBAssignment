# Program to find quotient and remainder of two numbers.

#To find the quotient and remainder of two numbers in Python, you can use built-in operators: the #floor division operator (//) for the quotient and the modulo operator (%) for the remainder. 
# // (floor division) returns the integer part of the division (the quotient).
# % (modulo) returns the remaining value after division (the remainder). 


# Define the two numbers (dividend and divisor)
dividend = 10
divisor = 3

# Calculate the quotient using floor division (//)
quotient = dividend // divisor

# Calculate the remainder using the modulo operator (%)
remainder = dividend % divisor

# Print the results
print(f"Dividend: {dividend}")
print(f"Divisor: {divisor}")
print(f"Quotient: {quotient}")
print(f"Remainder: {remainder}")
