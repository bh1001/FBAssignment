#Write a program to find maximum and minimum element in a list.
# Sample list of numbers
data_list = [34, 12, 56, 78, 23, 90, 45]

# Find the maximum element
maximum_element = max(data_list)

# Find the minimum element
minimum_element = min(data_list)

# Print the results
print(f"The list is: {data_list}")
print(f"Maximum element: {maximum_element}")
print(f"Minimum element: {minimum_element}")
